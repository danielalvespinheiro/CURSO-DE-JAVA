package aula198;

public class Pessoal {

	private String nome;
	private int num;
	
	public Pessoal(String nome, int num) {
		super();
		this.nome = nome;
		this.num = num;
	}
	
	public String getNome() {
		return nome;
	}
	public void setNome(String nome) {
		this.nome = nome;
	}
	public int getNum() {
		return num;
	}
	public void setNum(int num) {
		this.num = num;
	}
	
}
